int readingDailyGoal(int? minutes) =>
    minutes == null ? 0 : minutes.clamp(0, 1440);

String readingGoalCaption(int goalMinutes, int? todaySeconds) {
  final todayMinutes = (todaySeconds ?? 0) ~/ 60;
  if (goalMinutes <= 0) return '????????';
  if (todayMinutes >= goalMinutes) {
    return '??????? ? $todayMinutes / $goalMinutes ??';
  }
  return '???? $todayMinutes / $goalMinutes ??';
}
